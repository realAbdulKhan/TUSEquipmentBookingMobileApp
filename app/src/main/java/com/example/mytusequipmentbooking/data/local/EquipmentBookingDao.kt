
package com.example.mytusequipmentbooking.data.local

import androidx.room.Dao
import androidx.room.Insert
import androidx.room.OnConflictStrategy
import androidx.room.Query
import com.example.mytusequipmentbooking.model.Booking
import com.example.mytusequipmentbooking.model.Category
import com.example.mytusequipmentbooking.model.Equipment
import kotlinx.coroutines.flow.Flow


@Dao
interface EquipmentBookingDao {

    // OBSERVE CATEGORIES

    // SQL query that retrieves every record from the categories table.
    // Flow means the data is observed continuously.
    // When the categories table changes, the updated list is emitted automatically.
    // Used to display category information in the application.
    @Query("SELECT * FROM categories")
    fun observeCategories(): Flow<List<Category>>


    // OBSERVE EQUIPMENT

    // Retrieves every record from the equipment table.
    // Returns a Flow containing a list of Equipment objects.
    // When equipment is added, updated or deleted, Room emits the latest list.
    // This keeps the equipment catalogue screen updated automatically.
    @Query("SELECT * FROM equipment")
    fun observeEquipment(): Flow<List<Equipment>>


    // OBSERVE BOOKINGS

    // Retrieves every record from the bookings table.
    // Flow allows the application to react to changes in the bookings table.
    // Used by the My Bookings screen to display the user's bookings.
// Retrieves only bookings belonging to the specified Firebase user.
    @Query("SELECT * FROM bookings WHERE userUid = :userUid")
    fun observeBookings(userUid: String): Flow<List<Booking>>


    // COUNT CATEGORIES

    // SQL query that counts how many records currently exist in the categories table.
    // suspend means this function can run inside a coroutine without blocking the main thread.
    // Returns the number of categories as an Int.
    // Used by the Repository when checking whether sample categories need to be inserted.
    @Query("SELECT COUNT(*) FROM categories")
    suspend fun categoryCount(): Int


    // COUNT EQUIPMENT

    // Counts how many records currently exist in the equipment table.
    // Returns the total number of equipment records as an Int.
    // Used by the Repository to check whether the equipment table is empty.
    @Query("SELECT COUNT(*) FROM equipment")
    suspend fun equipmentCount(): Int


    // INSERT CATEGORIES

    // Inserts a list of categories into the categories table.
    // @Insert tells Room to generate the SQL INSERT operation.
    // OnConflictStrategy.REPLACE means an existing record with the same primary key
    // will be replaced rather than causing a conflict error.
    // suspend allows this database operation to run inside a coroutine.
    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertCategories(categories: List<Category>)


    // INSERT EQUIPMENT

    // Inserts a list of equipment records into the equipment table.
    // REPLACE handles conflicts by replacing an existing record with the same primary key.
    // Used when inserting the initial sample equipment through the Repository.
    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertEquipment(equipment: List<Equipment>)


    // INSERT NEW EQUIPMENT

    // Inserts one new equipment record into the equipment table.
    // Returns a Long containing the ID generated by Room for the new record.
    // This is used when the user adds equipment through the Add Equipment dialog.
    // The Repository receives this generated ID.
    @Insert
    suspend fun insertNewEquipment(equipment: Equipment): Long


    // DELETE EQUIPMENT

    // SQL query that deletes equipment from the equipment table
    // where the id matches the equipmentId passed into this function.
    // Used when the user confirms that they want to delete equipment.
    // suspend allows the delete operation to run inside a coroutine.
    @Query("DELETE FROM equipment WHERE id = :equipmentId")
    suspend fun deleteEquipment(equipmentId: Int)


    // INSERT A BOOKING

    // Inserts a new booking record into the bookings table.
    // The Booking object contains details such as equipment ID,
    // user ID, duration, purpose and booking status.
    // Returns a Long containing the generated booking ID.
    @Insert
    suspend fun insertBooking(booking: Booking): Long


    // UPDATE BOOKING STATUS

    // SQL query that updates the status column in the bookings table.
    // It only updates the booking whose id matches bookingId.
    // :status and :bookingId are parameters supplied when this function is called.
    // Used when a user cancels a booking.
    // The Repository/ViewModel can pass "Cancelled" as the new status.
    // Updates a booking only if it belongs to the specified user.
    @Query("""
    UPDATE bookings
    SET status = :status
    WHERE id = :bookingId AND userUid = :userUid
""")
    suspend fun updateBookingStatus(
        bookingId: Int,
        userUid: String,
        status: String
    )
}
